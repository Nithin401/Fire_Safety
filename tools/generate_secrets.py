"""Generate the ignored ESP1 secrets header from secrets/.env without logging values."""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / "secrets" / ".env"
OUTPUT = ROOT / "firmware" / "esp1_detection" / "secrets.h"
REQUIRED = {
    "WIFI_SSID": "WIFI_SSID",
    "WIFI_PASSWORD": "WIFI_PASSWORD",
    "THINGSPEAK_API_KEY": "THINGSPEAK_API_KEY",
    "FIREBASE_API_KEY": "FIREBASE_API_KEY",
    "FIREBASE_DATABASE_URL": "FIREBASE_DATABASE_URL",
    "FIREBASE_USER_EMAIL": "FIREBASE_DEVICE_EMAIL",
    "FIREBASE_USER_PASSWORD": "FIREBASE_DEVICE_PASSWORD",
}


def load_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def is_placeholder(value: str) -> bool:
    return not value or any(token in value.upper() for token in ("YOUR_", "REPLACE_", "CHANGE_ME", "<"))


def escape_c(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    values = load_env(ENV_FILE)
    missing = [env_key for _, env_key in REQUIRED.items() if is_placeholder(values.get(env_key, ""))]
    if missing:
        print("FAILED: required secret variables are missing or placeholders: " + ", ".join(missing))
        print("Fill secrets/.env from secrets/.env.example. Values are intentionally not shown.")
        return 1

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = ["#pragma once", "", "// Generated by tools/generate_secrets.py. Do not edit or commit."]
    for header_key, env_key in REQUIRED.items():
        lines.append(f'#define {header_key} "{escape_c(values[env_key])}"')
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"PASSED: generated ignored header at {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
